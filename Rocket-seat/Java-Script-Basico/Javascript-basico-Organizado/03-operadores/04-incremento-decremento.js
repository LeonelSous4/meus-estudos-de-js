// INCREMENTO E DECREMENTO
// ++ aumenta 1
// -- diminui 1

let numero = 10;

numero++; // agora vale 11
console.log(numero);

console.log(numero++); // mostra 11 e só depois aumenta
console.log(numero);   // agora vale 12

let valor = 20;
console.log(--valor);   // diminui antes de mostrar

let preco = 10;
preco += 5;             // soma 5
console.log(preco);

preco -= 2;             // subtrai 2
console.log(preco);
