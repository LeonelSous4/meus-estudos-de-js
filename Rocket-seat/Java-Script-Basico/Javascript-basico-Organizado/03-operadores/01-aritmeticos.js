// OPERADORES ARITMÉTICOS
// Usados para fazer cálculos.

console.log(2 + 2);   // soma
console.log(20 - 3);  // subtração
console.log(10 * 5);  // multiplicação
console.log(20 / 2);  // divisão
console.log(10 ** 2); // exponenciação
console.log(20 % 3);  // resto da divisão

// Exemplo útil:
// se o resto da divisão por 2 for zero, o número é par.
console.log(20 % 2 === 0); // true
