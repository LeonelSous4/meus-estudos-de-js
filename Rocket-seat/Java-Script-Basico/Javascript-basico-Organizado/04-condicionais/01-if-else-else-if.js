// IF, ELSE IF E ELSE
// Use quando uma decisão depende de condições.

let nota = 85;

if (nota >= 90) {
  console.log("Aprovado com excelência!");
} else if (nota >= 60) {
  console.log("Aprovado!");
} else {
  console.log("Reprovado.");
}

// Leitura mental:
// se isso acontecer -> execute
// senão, se outra coisa acontecer -> execute
// senão -> execute o bloco final
