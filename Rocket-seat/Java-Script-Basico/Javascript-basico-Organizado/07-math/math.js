// MATH
// Objeto nativo do JavaScript com várias utilidades matemáticas.

console.log(Math.abs(-5));       // valor absoluto
console.log(Math.ceil(4.1));      // arredonda para cima
console.log(Math.floor(4.9));     // arredonda para baixo
console.log(Math.round(4.5));     // arredonda para o mais próximo
console.log(Math.trunc(4.9));     // remove a parte decimal
console.log(Math.pow(2, 3));      // potência
console.log(Math.sqrt(25));       // raiz quadrada
console.log(Math.min(1, 7, -2));  // menor valor
console.log(Math.max(1, 7, -2));  // maior valor
console.log(Math.random());       // número aleatório entre 0 e 1
console.log(Math.PI);             // valor de PI
