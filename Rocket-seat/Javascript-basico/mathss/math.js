



// Método / Propriedade,O que faz?,Exemplo de Uso,Resultado
// Math.abs(x),Retorna o valor absoluto (positivo).,Math.abs(-5),5
// Math.ceil(x),Arredonda para cima (teto).,Math.ceil(4.1),5
// Math.floor(x),Arredonda para baixo (chão).,Math.floor(4.9),4
// Math.round(x),Arredonda para o mais próximo.,Math.round(4.5),5
// Math.trunc(x),Remove a parte decimal.,Math.trunc(4.9),4
// "Math.pow(b, e)",Potência (base elevada ao expoente).,"Math.pow(2, 3)",8
// Math.sqrt(x),Raiz quadrada.,Math.sqrt(25),5
// "Math.min(a, b...)",Retorna o menor valor da lista.,"Math.min(1, 7, -2)",-2
// "Math.max(a, b...)",Retorna o maior valor da lista.,"Math.max(1, 7, -2)",7
// Math.random(),Número aleatório entre 0 e 1.,Math.random(),0.548...
// Math.PI,Valor da constante PI.,Math.PI,3.14159...
// Math.sin(x),Seno de um número (em radianos).,Math.sin(0),0