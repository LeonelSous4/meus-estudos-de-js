// operadores aritmeticos
// + soma
console.log(`soma ${2 + 2}`);

// - subtração
console.log(`subtração ${20 - 2}`);

//  / divisão
console.log(`divisão ${20 / 2}`);

//  * mutiplicação
console.log(`multiplicação ${2 * 2}`);

// ** exponencial
console.log(`exponencial ${10 ** 2}`);


// numero % 2 para saber se a divisão tem resto
console.log(`resto da divisão ${20 % 2}`);

// para saber se o numero e par, se der true e par, se der false e impar
console.log(`esse numero e par? ${20 % 2 === 0}`);


