

 function sum(a, b) {
    return a + b
}


function multiply(a, b) {
    return a * b
}
// exportando com um nome diferente do nome da função, ou seja, renomeando a exportação, para isso basta usar a palavra reservada as, seguida do nome que queremos dar a exportação

export {
    sum as soma,
    multiply as multiplicar
}















