// default export, só pode ter um por arquivo, e é o valor padrão do módulo, ou seja, quando importamos o módulo sem especificar o que queremos, ele retorna o valor do default export

// função padrao fornecida pelo modulo

export default function sum(a, b) {
    return a + b
}

// nomeada - cada item e iportado pelo seu prprio nome de exporetação

export function multiply(a, b) {
    return a * b
}
















